// Test Data Builder for users (ADR 0007). Usernames are unique in a realm (R1 of the users
// contract), so each carries a prefix and a random suffix from the seeded faker. The prefix keeps
// the users of one spec file apart from another's: each author gets its own (L-60). Keycloak
// stores usernames in lower case, so the builder writes them that way.
import type { Faker } from '@faker-js/faker';
import type { NewUser } from '../types';

/** The realm the pack imports (`realm/qa-realm.json`). */
export const REALM = 'qa';

/** An id no user has: the nil UUID. */
export const UNKNOWN_ID = '00000000-0000-0000-0000-000000000000';

const suffix = (faker: Faker) => faker.string.alphanumeric({ length: 10, casing: 'lower' });

/** A unique username under `prefix` (lower case letters, digits and hyphens). */
export function aUsername(faker: Faker, prefix = 'qa-users'): string {
  return `${prefix}-${suffix(faker)}`;
}

/** A user with a unique username, an e-mail at a reserved domain and a first and last name. */
export function aUser(
  faker: Faker,
  overrides: Partial<NewUser> = {},
  prefix = 'qa-users',
): NewUser {
  const username = overrides.username ?? aUsername(faker, prefix);
  return {
    username,
    email: `${username}@example.com`,
    firstName: faker.person.firstName(),
    lastName: faker.person.lastName(),
    enabled: true,
    ...overrides,
  };
}

/**
 * `user` with a password credential, generated by the seeded faker for this run only, so a case can
 * prove a read does not expose what the user stored (TC-USERS-15).
 */
export function withPasswordCredential(user: NewUser, faker: Faker): NewUser {
  const generated = faker.internet.password({ length: 20 });
  return { ...user, credentials: [{ type: 'password', value: generated, temporary: false }] };
}

/** A realm name no realm has. */
export function unknownRealm(faker: Faker): string {
  return `missing-realm-${suffix(faker)}`;
}
