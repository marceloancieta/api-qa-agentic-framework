#!/usr/bin/env node
/**
 * Checks the decision tables of a pack (services/<pack>/rules/*.yaml) and generates the module specs
 * import them from (services/<pack>/generated/decision-tables.ts). Specs must not read files while
 * they are being collected (L-24), so the YAML reaches them as generated code.
 *
 * A table is refused when a combination of conditions has no rule or two disagreeing rules
 * (scripts/lib/decision-table.mjs). The table id is the file name.
 *
 *   node scripts/derive-decision-tables.mjs [--service <pack>]            report the tables
 *   node scripts/derive-decision-tables.mjs [--service <pack>] --write    write the generated module
 *   node scripts/derive-decision-tables.mjs [--service <pack>] --check    exit 1 when it is stale
 *
 * Without --service every pack is processed. A pack without rules/ needs no module; a module
 * left behind after its rules were removed is stale.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse as parseYaml } from 'yaml';
import { parseCli, readService, readTextIfExists, REPO_ROOT, servicePacks } from './lib/cli.mjs';
import { normalizeTable, tableProblems } from './lib/decision-table.mjs';

const GENERATED = join('generated', 'decision-tables.ts');

/** The pack's tables, by id, and every problem found in them. */
export function readTables(packDir) {
  const dir = join(packDir, 'rules');
  const tables = {};
  const problems = [];
  if (!existsSync(dir)) return { tables, problems };
  for (const file of readdirSync(dir)
    .filter((f) => /\.ya?ml$/.test(f))
    .sort()) {
    const id = file.replace(/\.ya?ml$/, '');
    let table;
    try {
      table = parseYaml(readFileSync(join(dir, file), 'utf8'));
    } catch (error) {
      problems.push(`rules/${file}: not valid YAML: ${error.message}`);
      continue;
    }
    const found = tableProblems(table, `rules/${file}`);
    if (found.length > 0) problems.push(...found);
    else tables[id] = normalizeTable(table);
  }
  return { tables, problems };
}

/** The generated module's text. */
export function moduleSource(pack, tables) {
  return [
    `// Generated by scripts/derive-decision-tables.mjs from services/${pack}/rules/*.yaml.`,
    `// Do not edit by hand; regenerate with \`npm run contract:decision-tables\`.`,
    '',
    "import type { DecisionTable } from '../../../helpers/decision-table';",
    '',
    `export const decisionTables = ${JSON.stringify(tables, null, 2)} as const satisfies Record<string, DecisionTable>;`,
    '',
  ].join('\n');
}

/** Process one pack: returns `{ pack, tables, problems, stale }`, writing when asked. */
export async function processPack(
  pack,
  { root = REPO_ROOT, write = false, format = async (text) => text } = {},
) {
  const { dir } = readService(pack, root);
  const { tables, problems } = readTables(dir);
  const target = join(dir, GENERATED);
  const wanted = Object.keys(tables).length > 0 ? await format(moduleSource(pack, tables)) : null;
  const current = readTextIfExists(target);
  const differs = problems.length === 0 && wanted !== current;
  if (write && differs) {
    if (wanted === null) rmSync(target);
    else {
      mkdirSync(join(dir, 'generated'), { recursive: true });
      writeFileSync(target, wanted);
    }
  }
  return { pack, tables, problems, stale: differs && !write };
}

/** Formats generated code the way the repository's prettier configuration does. */
async function prettierFormat() {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(join(REPO_ROOT, 'services', GENERATED))) ?? {};
  return (text) => prettier.format(text, { ...options, parser: 'typescript' });
}

async function main() {
  const values = parseCli({
    write: { type: 'boolean', default: false },
    check: { type: 'boolean', default: false },
  });
  const packs = values.service ? [values.service] : servicePacks(REPO_ROOT);
  const format = await prettierFormat();
  let failed = false;
  for (const pack of packs) {
    const outcome = await processPack(pack, { write: values.write, format });
    for (const problem of outcome.problems) console.error(`${pack}: ${problem}`);
    const count = Object.keys(outcome.tables).length;
    if (outcome.problems.length > 0) {
      failed = true;
    } else if (values.check && outcome.stale) {
      failed = true;
      console.error(`${pack}: ${GENERATED} is stale; run npm run contract:decision-tables.`);
    } else {
      const state = values.write ? 'written' : values.check ? 'current' : 'checked';
      console.log(`${pack}: ${count} decision table(s)${count > 0 ? ` ${state}` : ''}.`);
    }
  }
  process.exitCode = failed ? 1 : 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(2);
  });
}
