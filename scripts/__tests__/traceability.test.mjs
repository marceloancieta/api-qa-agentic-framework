// traceability (GATE-05): the matrix built from the coverage-status fixture repository, its
// Markdown against a reviewed copy, the two gap lists and the --write contract.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildMatrix, renderPack, resultWord } from '../traceability.mjs';
import { REPO_ROOT } from '../lib/cli.mjs';

const ROOT = join(import.meta.dirname, '..', '__fixtures__', 'coverage-status');
const EXPECTED_MD = join(import.meta.dirname, '..', '__fixtures__', 'traceability', 'shop.md');
const SCRIPT = join(import.meta.dirname, '..', 'traceability.mjs');
const run = (...args) => spawnSync(process.execPath, [SCRIPT, ...args], { encoding: 'utf8' });
const expected = () => readFileSync(EXPECTED_MD, 'utf8').replace(/\r\n/g, '\n');

test('requirement -> case -> technique -> spec -> status -> last result -> defect', () => {
  const [pack] = buildMatrix(ROOT)['packs'];
  const [items] = pack['registries'];
  assert.deepEqual(
    items['rows'].map((r) => [
      r['requirement'],
      r['case'],
      r['technique'],
      r['specs'],
      r['status'],
      r['lastResult'],
      r['defect'],
    ]),
    [
      ['REQ-ITEM-01', 'TC-ITEM-01', 'equivalence-partition', [], 'draft', 'not run', null],
      [
        'REQ-ITEM-01',
        'TC-ITEM-03',
        'equivalence-partition',
        ['services/shop/specs/items.spec.ts:8'],
        'automated',
        'failed',
        null,
      ],
      [
        'REQ-ITEM-02',
        'TC-ITEM-08',
        'use-case',
        ['services/shop/specs/items.spec.ts:16'],
        'published',
        'passed',
        null,
      ],
      [
        'REQ-ITEM-02',
        'TC-ITEM-09',
        'decision-table',
        ['services/shop/specs/items.spec.ts:18'],
        'published',
        'not run',
        null,
      ],
    ],
  );
});

test('uncovered requirements and cases without a requirement are listed apart', () => {
  const [items, stock] = buildMatrix(ROOT)['packs'][0]['registries'];
  assert.deepEqual(
    items['uncovered'].map((r) => r['id']),
    ['REQ-ITEM-03'],
  );
  assert.deepEqual(
    items['unlinked'].map((r) => r['case']),
    ['02', '04', '05', '06', '07', '10', '11', '12', '13', '14', '15'].map((n) => `TC-ITEM-${n}`),
  );
  const blocked = items['unlinked'].find((r) => r['case'] === 'TC-ITEM-10');
  assert.deepEqual([blocked['lastResult'], blocked['defect']], ['skipped', 'BUG-10']);
  assert.equal(stock['problems'], 1);
  assert.deepEqual(
    stock['unlinked'].map((r) => r['case']),
    ['TC-STK-01'],
  );
});

test('the Markdown matches the reviewed copy', () => {
  const matrix = buildMatrix(ROOT);
  assert.equal(renderPack(matrix, matrix['packs'][0]), expected());
});

test('without results every case reads "not run" and the document says why', () => {
  const matrix = buildMatrix(ROOT, { resultsDir: join(ROOT, 'no-such-results') });
  const text = renderPack(matrix, matrix['packs'][0]);
  assert.match(text, /no result files in `no-such-results`, so every case reads "not run"/);
  assert.ok(!/\| (passed|failed|skipped) \|/.test(text));
});

test('allure statuses map to the matrix wording', () => {
  assert.deepEqual(
    ['passed', 'failed', 'broken', 'skipped', 'unknown', undefined].map(resultWord),
    ['passed', 'failed', 'failed', 'skipped', 'not run', 'not run'],
  );
});

test('cli --write generates docs/traceability/<pack>.md with its header', () => {
  const copy = mkdtempSync(join(tmpdir(), 'traceability-'));
  try {
    cpSync(ROOT, copy, { recursive: true });
    const result = run('--root', copy, '--write');
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /shop: wrote docs\/traceability\/shop\.md/);
    const written = readFileSync(join(copy, 'docs', 'traceability', 'shop.md'), 'utf8');
    assert.equal(written, expected());
    assert.match(written, /^<!-- Generated by scripts\/traceability\.mjs/);
  } finally {
    rmSync(copy, { recursive: true, force: true });
  }
});

test('cli prints Markdown or JSON', () => {
  assert.equal(run('--root', ROOT).stdout, expected());
  assert.equal(JSON.parse(run('--root', ROOT, '--json').stdout)['packs'][0]['pack'], 'shop');
});

test('a tree without registries passes cleanly, and so does the repository', () => {
  const empty = mkdtempSync(join(tmpdir(), 'traceability-'));
  try {
    const bare = run('--root', empty);
    assert.equal(bare.status, 0, bare.stderr);
    assert.match(bare.stdout, /No registries under services\/\*\/registry\/ yet/);
  } finally {
    rmSync(empty, { recursive: true, force: true });
  }
  const repo = run('--root', REPO_ROOT);
  assert.equal(repo.status, 0, repo.stderr);
  assert.doesNotMatch(repo.stdout, /No registries/);
});
